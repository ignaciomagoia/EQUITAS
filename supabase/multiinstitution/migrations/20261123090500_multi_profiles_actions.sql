select public.assert_multiinstitution_platform();

create table public.debtor_profile (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  debtor_id bigint not null,
  total_debt_amount numeric not null default 0 check (total_debt_amount >= 0),
  overdue_debt_amount numeric not null default 0 check (overdue_debt_amount >= 0),
  debt_count integer not null default 0 check (debt_count >= 0),
  overdue_debt_count integer not null default 0 check (overdue_debt_count >= 0),
  oldest_debt_days integer not null default 0 check (oldest_debt_days >= 0),
  average_debt_age_days integer not null default 0 check (average_debt_age_days >= 0),
  active_person_count integer not null default 0 check (active_person_count >= 0),
  available_contact_count integer not null default 0 check (available_contact_count >= 0),
  previous_contact_count integer not null default 0 check (previous_contact_count >= 0),
  previous_response_count integer not null default 0 check (previous_response_count >= 0),
  socioeconomic_risk_level integer not null default 0 check (socioeconomic_risk_level between 0 and 100),
  profile_generated_at timestamp with time zone,
  active boolean not null default true,
  unique (institution_id, debtor_id),
  unique (id, institution_id),
  foreign key (debtor_id, institution_id)
    references public.debtor(id, institution_id) on delete restrict
);

create table public.debtor_profile_detail (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  debtor_profile_id bigint not null,
  person_id bigint not null,
  risk_value numeric not null default 0 check (risk_value between 0 and 100),
  reason text,
  active boolean not null default true,
  unique (institution_id, debtor_profile_id, person_id),
  foreign key (debtor_profile_id, institution_id)
    references public.debtor_profile(id, institution_id) on delete restrict,
  foreign key (person_id, institution_id)
    references public.person(id, institution_id) on delete restrict
);

create table public.collection_action (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  debtor_id bigint not null,
  person_id bigint,
  created_by uuid not null references public.app_user(id) on delete restrict,
  action_type text not null,
  recommendation_code text,
  status text not null default 'PENDING' check (status in ('PENDING', 'COMPLETED', 'CANCELLED')),
  outcome text,
  notes text,
  scheduled_at timestamp with time zone,
  completed_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  foreign key (debtor_id, institution_id)
    references public.debtor(id, institution_id) on delete restrict,
  foreign key (person_id, institution_id)
    references public.person(id, institution_id) on delete restrict
);

create index debtor_profile_institution_risk_idx
  on public.debtor_profile (institution_id, socioeconomic_risk_level desc);
create index debtor_profile_detail_institution_risk_idx
  on public.debtor_profile_detail (institution_id, risk_value desc);
create index collection_action_institution_status_idx
  on public.collection_action (institution_id, status, created_at desc);

grant all on public.debtor_profile, public.debtor_profile_detail, public.collection_action to service_role;

notify pgrst, 'reload schema';
