select public.assert_multiinstitution_platform();

create table public.institution (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null,
  legal_name text,
  institution_type text not null default 'MUNICIPALITY',
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'SUSPENDED', 'ARCHIVED')),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create table public.app_user (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'SUSPENDED')),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique (email)
);

create table public.platform_role (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text,
  active boolean not null default true
);

create table public.institution_role (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text,
  active boolean not null default true
);

create table public.permission (
  code text primary key,
  scope text not null check (scope in ('PLATFORM', 'INSTITUTION')),
  description text not null
);

create table public.platform_role_permission (
  role_id bigint not null references public.platform_role(id) on delete cascade,
  permission_code text not null references public.permission(code) on delete cascade,
  primary key (role_id, permission_code)
);

create table public.institution_role_permission (
  role_id bigint not null references public.institution_role(id) on delete cascade,
  permission_code text not null references public.permission(code) on delete cascade,
  primary key (role_id, permission_code)
);

create table public.platform_user_role (
  user_id uuid not null references public.app_user(id) on delete cascade,
  role_id bigint not null references public.platform_role(id) on delete restrict,
  granted_by uuid references public.app_user(id) on delete set null,
  granted_at timestamp with time zone not null default now(),
  primary key (user_id, role_id)
);

create table public.institution_membership (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  user_id uuid not null references public.app_user(id) on delete restrict,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'SUSPENDED', 'REVOKED')),
  granted_by uuid references public.app_user(id) on delete set null,
  granted_at timestamp with time zone not null default now(),
  revoked_at timestamp with time zone,
  updated_at timestamp with time zone not null default now(),
  unique (institution_id, user_id),
  unique (id, institution_id)
);

create table public.institution_membership_role (
  membership_id bigint not null,
  institution_id bigint not null,
  role_id bigint not null references public.institution_role(id) on delete restrict,
  granted_by uuid references public.app_user(id) on delete set null,
  granted_at timestamp with time zone not null default now(),
  primary key (membership_id, role_id),
  foreign key (membership_id, institution_id)
    references public.institution_membership(id, institution_id) on delete cascade
);

create table public.user_active_institution (
  user_id uuid primary key references public.app_user(id) on delete cascade,
  institution_id bigint not null,
  selected_at timestamp with time zone not null default now(),
  foreign key (institution_id, user_id)
    references public.institution_membership(institution_id, user_id) on delete cascade
);

create index institution_membership_user_active_idx
  on public.institution_membership (user_id, institution_id)
  where status = 'ACTIVE';

