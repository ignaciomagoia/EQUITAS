select public.assert_multiinstitution_platform();

create table public.currency (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z]{3}$'),
  name text not null,
  active boolean not null default true
);

create table public.document_type (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  active boolean not null default true
);

create table public.person_type (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  active boolean not null default true
);

create table public.contact_type (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  priority integer,
  active boolean not null default true
);

create table public.province (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true
);

create table public.city (
  id bigint generated by default as identity primary key,
  province_id bigint not null references public.province(id) on delete restrict,
  name text not null,
  postal_code text,
  active boolean not null default true,
  unique (province_id, name, postal_code)
);

create table public.institution_object_type (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  code text not null,
  name text not null,
  active boolean not null default true,
  unique (institution_id, code),
  unique (id, institution_id)
);

create table public.institution_debt_status (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  code text not null,
  name text not null,
  description text,
  active boolean not null default true,
  unique (institution_id, code),
  unique (id, institution_id)
);

create table public.institution_data_source (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  name text not null,
  source_kind text not null default 'CSV',
  active boolean not null default true,
  unique (institution_id, name),
  unique (id, institution_id)
);

insert into public.currency (code, name) values ('ARS', 'Peso argentino') on conflict (code) do nothing;
insert into public.document_type (code, name) values
  ('DNI', 'Documento Nacional de Identidad'), ('CUIT', 'Clave Unica de Identificacion Tributaria'),
  ('CUIL', 'Codigo Unico de Identificacion Laboral'), ('OTHER', 'Otro')
on conflict (code) do nothing;
insert into public.person_type (code, name) values
  ('INDIVIDUAL', 'Persona humana'), ('LEGAL_ENTITY', 'Persona juridica'), ('UNKNOWN', 'No informado')
on conflict (code) do nothing;
insert into public.contact_type (code, name, priority) values
  ('PHONE', 'Telefono', 1), ('MOBILE', 'Celular', 2), ('EMAIL', 'Correo electronico', 3), ('WHATSAPP', 'WhatsApp', 4)
on conflict (code) do nothing;

grant all on public.currency, public.document_type, public.person_type, public.contact_type,
  public.province, public.city, public.institution_object_type, public.institution_debt_status,
  public.institution_data_source to service_role;

notify pgrst, 'reload schema';
