create index import_row_error_job_row_idx on public.import_row_error (job_id, source_row);

create table public.import_change (
  id bigint generated by default as identity primary key,
  job_id bigint not null,
  institution_id bigint not null,
  debtor_id bigint not null,
  debt_id bigint,
  debt_identity_hash text not null check (debt_identity_hash ~ '^[a-f0-9]{64}$'),
  change_type text not null check (change_type in ('INSERTED', 'UPDATED')),
  before_values jsonb,
  after_values jsonb not null check (jsonb_typeof(after_values) = 'object'),
  created_at timestamp with time zone not null default now(),
  unique (job_id, debtor_id, debt_identity_hash),
  check ((change_type = 'UPDATED' and before_values is not null) or (change_type = 'INSERTED' and before_values is null)),
  foreign key (job_id, institution_id)
    references public.import_job(id, institution_id) on delete cascade,
  foreign key (debtor_id, institution_id)
    references public.debtor(id, institution_id) on delete restrict,
  foreign key (debt_id, institution_id)
    references public.debt(id, institution_id) on delete set null
);

create index import_change_job_idx on public.import_change (job_id, change_type);

create table public.import_audit_event (
  id bigint generated by default as identity primary key,
  job_id bigint not null,
  institution_id bigint not null,
  requested_by uuid not null references public.app_user(id) on delete restrict,
  event_type text not null check (event_type in ('CREATED', 'STATUS_CHANGED')),
  status text not null,
  mode text not null check (mode in ('DRY_RUN', 'APPLY')),
  content_sha256 text not null check (content_sha256 ~ '^[a-f0-9]{64}$'),
  total_rows integer not null check (total_rows >= 0),
  processed_rows integer not null check (processed_rows >= 0),
  inserted_rows integer not null check (inserted_rows >= 0),
  updated_rows integer not null check (updated_rows >= 0),
  unchanged_rows integer not null check (unchanged_rows >= 0),
  rejected_rows integer not null check (rejected_rows >= 0),
  occurred_at timestamp with time zone not null default now(),
  foreign key (job_id, institution_id)
    references public.import_job(id, institution_id) on delete cascade
);

create index import_audit_event_job_occurred_idx on public.import_audit_event (job_id, occurred_at);

create or replace function public.record_import_audit_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' or old.status is distinct from new.status then
    insert into public.import_audit_event (
      job_id, institution_id, requested_by, event_type, status, mode, content_sha256,
      total_rows, processed_rows, inserted_rows, updated_rows, unchanged_rows, rejected_rows
    ) values (
      new.id, new.institution_id, new.requested_by,
      case when tg_op = 'INSERT' then 'CREATED' else 'STATUS_CHANGED' end,
      new.status, new.mode, new.content_sha256, new.total_rows, new.processed_rows,
      new.inserted_rows, new.updated_rows, new.unchanged_rows, new.rejected_rows
    );
  end if;
  return new;
end;
$$;

create trigger import_job_audit_trigger
after insert or update of status on public.import_job
for each row execute function public.record_import_audit_event();

grant all on public.import_control, public.import_authorization, public.import_job,
  public.import_stage_row, public.import_row_error, public.import_change,
  public.import_audit_event to service_role;
revoke all on function public.record_import_audit_event() from public, anon, authenticated;
grant execute on function public.record_import_audit_event() to service_role;

notify pgrst, 'reload schema';
