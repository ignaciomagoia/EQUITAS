create table public.import_control (
  institution_id bigint primary key references public.institution(id) on delete restrict,
  apply_enabled boolean not null default false,
  updated_at timestamp with time zone not null default now()
);

create table public.import_authorization (
  institution_id bigint not null,
  membership_id bigint not null,
  can_import boolean not null default false,
  can_apply boolean not null default false,
  active boolean not null default true,
  granted_by uuid references public.app_user(id) on delete set null,
  granted_at timestamp with time zone not null default now(),
  revoked_at timestamp with time zone,
  updated_at timestamp with time zone not null default now(),
  primary key (institution_id, membership_id),
  check (not can_apply or can_import),
  foreign key (membership_id, institution_id)
    references public.institution_membership(id, institution_id) on delete restrict
);

create table public.import_job (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  requested_by uuid not null references public.app_user(id) on delete restrict,
  profile_version_id bigint not null,
  file_name text not null,
  storage_path text not null unique,
  content_sha256 text not null check (content_sha256 ~ '^[a-f0-9]{64}$'),
  file_size_bytes bigint not null check (file_size_bytes > 0),
  mode text not null check (mode in ('DRY_RUN', 'APPLY')),
  status text not null check (status in (
    'UPLOADING', 'QUEUED', 'VALIDATING', 'STAGING', 'MERGING', 'RECALCULATING_PROFILES',
    'DRY_RUN_COMPLETED', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED', 'CANCELLED'
  )),
  total_rows integer not null default 0 check (total_rows >= 0),
  processed_rows integer not null default 0 check (processed_rows >= 0),
  inserted_rows integer not null default 0 check (inserted_rows >= 0),
  updated_rows integer not null default 0 check (updated_rows >= 0),
  unchanged_rows integer not null default 0 check (unchanged_rows >= 0),
  rejected_rows integer not null default 0 check (rejected_rows >= 0),
  ignored_columns jsonb not null default '[]'::jsonb check (jsonb_typeof(ignored_columns) = 'array'),
  profile_snapshot jsonb not null default '{}'::jsonb check (jsonb_typeof(profile_snapshot) = 'object'),
  error_message text,
  worker_id text,
  lock_expires_at timestamp with time zone,
  attempt_count integer not null default 0 check (attempt_count >= 0),
  merge_completed_at timestamp with time zone,
  profiles_recalculated_at timestamp with time zone,
  profile_recalculation_attempt_count integer not null default 0 check (profile_recalculation_attempt_count >= 0),
  profile_recalculation_error text,
  started_at timestamp with time zone,
  completed_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique (id, institution_id),
  foreign key (profile_version_id, institution_id)
    references public.import_profile_version(id, institution_id) on delete restrict
);

create unique index import_job_one_active_institution_idx
  on public.import_job (institution_id)
  where status in ('UPLOADING', 'QUEUED', 'VALIDATING', 'STAGING', 'MERGING', 'RECALCULATING_PROFILES');
create index import_job_institution_created_idx on public.import_job (institution_id, created_at desc);
create index import_job_institution_hash_idx on public.import_job (institution_id, content_sha256, created_at desc);
create index import_job_profile_recovery_idx
  on public.import_job (institution_id, merge_completed_at, profiles_recalculated_at, updated_at)
  where merge_completed_at is not null and profiles_recalculated_at is null;

create table public.import_stage_row (
  id bigint generated by default as identity primary key,
  job_id bigint not null,
  institution_id bigint not null,
  source_row integer not null check (source_row >= 2),
  raw_values jsonb not null check (jsonb_typeof(raw_values) = 'object'),
  normalized_values jsonb not null check (jsonb_typeof(normalized_values) = 'object'),
  provided_fields text[] not null default '{}',
  debtor_identity_hash text check (debtor_identity_hash ~ '^[a-f0-9]{64}$'),
  debt_identity_hash text check (debt_identity_hash ~ '^[a-f0-9]{64}$'),
  person_identity_hash text check (person_identity_hash ~ '^[a-f0-9]{64}$'),
  debtor_id bigint,
  debt_id bigint,
  person_id bigint,
  validation_status text not null default 'PENDING' check (validation_status in ('PENDING', 'VALID', 'REJECTED')),
  created_at timestamp with time zone not null default now(),
  unique (job_id, source_row),
  unique (job_id, debtor_identity_hash, debt_identity_hash),
  foreign key (job_id, institution_id)
    references public.import_job(id, institution_id) on delete cascade,
  foreign key (debtor_id, institution_id)
    references public.debtor(id, institution_id) on delete restrict,
  foreign key (debt_id, institution_id)
    references public.debt(id, institution_id) on delete restrict,
  foreign key (person_id, institution_id)
    references public.person(id, institution_id) on delete restrict
);

create index import_stage_row_job_valid_idx
  on public.import_stage_row (job_id, validation_status, debtor_id);

create table public.import_row_error (
  id bigint generated by default as identity primary key,
  job_id bigint not null,
  institution_id bigint not null,
  source_row integer not null check (source_row >= 2),
  code text not null,
  message text not null,
  source_key jsonb not null default '{}'::jsonb check (jsonb_typeof(source_key) = 'object'),
  created_at timestamp with time zone not null default now(),
  unique (job_id, source_row, code),
  foreign key (job_id, institution_id)
    references public.import_job(id, institution_id) on delete cascade
