create table public.import_identity_scheme (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  entity_kind text not null check (entity_kind in ('DEBTOR', 'DEBT', 'PERSON')),
  code text not null,
  display_name text not null,
  canonical_fields text[] not null check (cardinality(canonical_fields) > 0),
  normalizer_version text not null default 'v1',
  active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  retired_at timestamp with time zone,
  unique (institution_id, entity_kind, code),
  unique (id, institution_id)
);

create table public.import_profile (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institution(id) on delete restrict,
  code text not null,
  display_name text not null,
  status text not null default 'DRAFT' check (status in ('DRAFT', 'ACTIVE', 'RETIRED')),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique (institution_id, code),
  unique (id, institution_id)
);

create table public.import_profile_version (
  id bigint generated by default as identity primary key,
  institution_id bigint not null,
  profile_id bigint not null,
  version_number integer not null check (version_number > 0),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'ACTIVE', 'RETIRED')),
  delimiter text not null check (delimiter in (',', ';', '\t')),
  encoding text not null check (encoding in ('UTF-8', 'UTF-8-SIG', 'WINDOWS-1252')),
  debtor_identity_scheme_id bigint not null,
  debt_identity_scheme_id bigint not null,
  person_identity_scheme_id bigint,
  created_at timestamp with time zone not null default now(),
  activated_at timestamp with time zone,
  unique (profile_id, version_number),
  unique (id, institution_id),
  foreign key (profile_id, institution_id)
    references public.import_profile(id, institution_id) on delete restrict,
  foreign key (debtor_identity_scheme_id, institution_id)
    references public.import_identity_scheme(id, institution_id) on delete restrict,
  foreign key (debt_identity_scheme_id, institution_id)
    references public.import_identity_scheme(id, institution_id) on delete restrict,
  foreign key (person_identity_scheme_id, institution_id)
    references public.import_identity_scheme(id, institution_id) on delete restrict
);

create table public.import_field_mapping (
  id bigint generated by default as identity primary key,
  profile_version_id bigint not null references public.import_profile_version(id) on delete cascade,
  canonical_field text not null,
  target_entity text not null check (target_entity in ('DEBTOR', 'DEBT', 'PERSON', 'CONTACT', 'ADDRESS')),
  source_headers text[] not null check (cardinality(source_headers) > 0),
  data_type text not null check (data_type in ('TEXT', 'DECIMAL', 'DATE', 'BOOLEAN', 'IDENTIFIER')),
  required_on_insert boolean not null default false,
  required_on_update boolean not null default false,
  active boolean not null default true,
  unique (profile_version_id, canonical_field)
);

create or replace function public.assert_import_profile_identity_schemes()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_debtor_kind text;
  v_debt_kind text;
  v_person_kind text;
begin
  select entity_kind into v_debtor_kind
  from public.import_identity_scheme
  where id = new.debtor_identity_scheme_id and institution_id = new.institution_id;

  select entity_kind into v_debt_kind
  from public.import_identity_scheme
  where id = new.debt_identity_scheme_id and institution_id = new.institution_id;

  if new.person_identity_scheme_id is not null then
    select entity_kind into v_person_kind
    from public.import_identity_scheme
    where id = new.person_identity_scheme_id and institution_id = new.institution_id;
  end if;

  if v_debtor_kind <> 'DEBTOR' or v_debt_kind <> 'DEBT' or
     (new.person_identity_scheme_id is not null and v_person_kind <> 'PERSON') then
    raise exception 'Los esquemas de identidad no corresponden a las entidades del perfil.';
  end if;

  return new;
end;
$$;

create or replace function public.protect_import_configuration_history()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_profile_status text;
  v_profile_version_id bigint;
begin
  if tg_table_name = 'import_identity_scheme' and
     (new.entity_kind, new.canonical_fields, new.normalizer_version) is distinct from
     (old.entity_kind, old.canonical_fields, old.normalizer_version) then
    raise exception 'Un esquema de identidad es inmutable. Cree uno nuevo y retire el anterior.';
  end if;

  if tg_table_name = 'import_profile_version' and old.status <> 'DRAFT' and
     (new.institution_id, new.profile_id, new.version_number, new.delimiter, new.encoding,
      new.debtor_identity_scheme_id, new.debt_identity_scheme_id, new.person_identity_scheme_id)
     is distinct from
     (old.institution_id, old.profile_id, old.version_number, old.delimiter, old.encoding,
      old.debtor_identity_scheme_id, old.debt_identity_scheme_id, old.person_identity_scheme_id) then
    raise exception 'Una version no borrador es inmutable. Cree una nueva version del perfil.';
  end if;

  if tg_table_name = 'import_field_mapping' then
    v_profile_version_id := case
      when tg_op = 'DELETE' then old.profile_version_id
      else new.profile_version_id
    end;

    select status into v_profile_status
    from public.import_profile_version
    where id = v_profile_version_id;

    if v_profile_status <> 'DRAFT' then
      raise exception 'Los mapeos solo se pueden modificar mientras la version esta en borrador.';
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

create trigger import_profile_identity_schemes_trigger
before insert or update of institution_id, debtor_identity_scheme_id, debt_identity_scheme_id, person_identity_scheme_id
on public.import_profile_version
for each row execute function public.assert_import_profile_identity_schemes();

create trigger import_identity_scheme_immutable_trigger
before update on public.import_identity_scheme
for each row execute function public.protect_import_configuration_history();

create trigger import_profile_version_immutable_trigger
before update on public.import_profile_version
for each row execute function public.protect_import_configuration_history();

create trigger import_field_mapping_draft_only_trigger
before insert or update or delete on public.import_field_mapping
for each row execute function public.protect_import_configuration_history();

create index import_profile_version_active_idx
  on public.import_profile_version (institution_id, profile_id)
  where status = 'ACTIVE';

grant all on public.import_identity_scheme, public.import_profile, public.import_profile_version,
  public.import_field_mapping to service_role;
revoke all on function public.assert_import_profile_identity_schemes() from public, anon, authenticated;
revoke all on function public.protect_import_configuration_history() from public, anon, authenticated;
grant execute on function public.assert_import_profile_identity_schemes() to service_role;
grant execute on function public.protect_import_configuration_history() to service_role;

notify pgrst, 'reload schema';
