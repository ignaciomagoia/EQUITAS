create table public.administration_audit_event (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references public.app_user(id) on delete set null,
  institution_id bigint references public.institution(id) on delete set null,
  event_type text not null,
  subject_type text not null,
  subject_id text,
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
  created_at timestamp with time zone not null default now()
);

create index administration_audit_event_institution_idx
  on public.administration_audit_event (institution_id, created_at desc);

create or replace function public.upsert_platform_app_user(
  p_user_id uuid,
  p_full_name text
)
returns public.app_user
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text;
  v_user public.app_user;
begin
  if not private.is_platform_admin() then
    raise exception 'Solo un administrador de EQUITAS puede administrar usuarios.';
  end if;

  select email into v_email from auth.users where id = p_user_id;
  if v_email is null then
    raise exception 'No existe el usuario de Supabase Auth indicado.';
  end if;

  if nullif(btrim(p_full_name), '') is null then
    raise exception 'El nombre completo es obligatorio.';
  end if;

  insert into public.app_user (id, full_name, email)
  values (p_user_id, btrim(p_full_name), v_email)
  on conflict (id) do update
    set full_name = excluded.full_name,
        email = excluded.email,
        updated_at = now()
  returning * into v_user;

  insert into public.administration_audit_event (actor_user_id, event_type, subject_type, subject_id)
  values (auth.uid(), 'APP_USER_UPSERTED', 'APP_USER', p_user_id::text);

  return v_user;
end;
$$;

create or replace function public.create_institution(
  p_slug text,
  p_name text,
  p_legal_name text,
  p_institution_type text,
  p_owner_user_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_institution_id bigint;
  v_membership_id bigint;
  v_admin_role_id bigint;
begin
  if not private.is_platform_admin() then
    raise exception 'Solo un administrador de EQUITAS puede crear instituciones.';
  end if;

  if not exists (select 1 from public.app_user where id = p_owner_user_id and status = 'ACTIVE') then
    raise exception 'El responsable institucional debe existir y estar activo.';
  end if;

  insert into public.institution (slug, name, legal_name, institution_type)
  values (lower(btrim(p_slug)), btrim(p_name), nullif(btrim(p_legal_name), ''), coalesce(nullif(btrim(p_institution_type), ''), 'MUNICIPALITY'))
  returning id into v_institution_id;

  insert into public.import_control (institution_id, apply_enabled)
  values (v_institution_id, false);

  insert into public.institution_membership (institution_id, user_id, granted_by)
  values (v_institution_id, p_owner_user_id, auth.uid())
  returning id into v_membership_id;

  select id into v_admin_role_id
  from public.institution_role
  where code = 'institution_admin' and active;

  if v_admin_role_id is null then
    raise exception 'No existe el rol institucional base.';
  end if;

  insert into public.institution_membership_role (membership_id, institution_id, role_id, granted_by)
  values (v_membership_id, v_institution_id, v_admin_role_id, auth.uid());

  insert into public.administration_audit_event (
    actor_user_id, institution_id, event_type, subject_type, subject_id, details
  ) values (
    auth.uid(), v_institution_id, 'INSTITUTION_CREATED', 'INSTITUTION', v_institution_id::text,
    jsonb_build_object('slug', lower(btrim(p_slug)), 'owner_user_id', p_owner_user_id)
  );

  return v_institution_id;
end;
$$;

create or replace function public.grant_institution_membership_role(
  p_institution_id bigint,
  p_user_id uuid,
  p_role_code text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_membership_id bigint;
  v_role_id bigint;
begin
  if not private.is_platform_admin() then
    raise exception 'Solo un administrador de EQUITAS puede asignar membresias o roles.';
  end if;

  if not exists (select 1 from public.institution where id = p_institution_id and status = 'ACTIVE') then
    raise exception 'La institucion indicada no existe o no esta activa.';
  end if;

  if not exists (select 1 from public.app_user where id = p_user_id and status = 'ACTIVE') then
    raise exception 'El usuario indicado no existe o no esta activo.';
  end if;

  select id into v_role_id
  from public.institution_role
  where code = p_role_code and active;
  if v_role_id is null then
    raise exception 'El rol institucional indicado no existe o no esta activo.';
  end if;

  insert into public.institution_membership (institution_id, user_id, status, granted_by, revoked_at)
  values (p_institution_id, p_user_id, 'ACTIVE', auth.uid(), null)
  on conflict (institution_id, user_id) do update
    set status = 'ACTIVE', revoked_at = null, granted_by = excluded.granted_by, updated_at = now()
  returning id into v_membership_id;

  insert into public.institution_membership_role (membership_id, institution_id, role_id, granted_by)
  values (v_membership_id, p_institution_id, v_role_id, auth.uid())
  on conflict do nothing;

  insert into public.administration_audit_event (
    actor_user_id, institution_id, event_type, subject_type, subject_id, details
  ) values (
    auth.uid(), p_institution_id, 'MEMBERSHIP_ROLE_GRANTED', 'APP_USER', p_user_id::text,
    jsonb_build_object('role_code', p_role_code)
  );

  return v_membership_id;
end;
$$;

create or replace function public.set_institution_import_authorization(
  p_institution_id bigint,
  p_membership_id bigint,
  p_can_import boolean,
  p_can_apply boolean,
  p_active boolean
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not private.is_platform_admin() then
    raise exception 'Solo un administrador de EQUITAS puede asignar permisos de importacion.';
  end if;

  if p_can_apply and not p_can_import then
    raise exception 'No se puede otorgar apply sin permiso de importacion.';
  end if;

  if not exists (
    select 1 from public.institution_membership
    where id = p_membership_id and institution_id = p_institution_id
  ) then
    raise exception 'La membresia no pertenece a la institucion indicada.';
  end if;

  insert into public.import_authorization (
    institution_id, membership_id, can_import, can_apply, active, granted_by, revoked_at, updated_at
  ) values (
    p_institution_id, p_membership_id, p_can_import, p_can_apply, p_active, auth.uid(),
    case when p_active then null else now() end, now()
  )
  on conflict (institution_id, membership_id) do update
    set can_import = excluded.can_import,
        can_apply = excluded.can_apply,
        active = excluded.active,
        granted_by = excluded.granted_by,
        revoked_at = excluded.revoked_at,
        updated_at = now();

  insert into public.administration_audit_event (
    actor_user_id, institution_id, event_type, subject_type, subject_id, details
  ) values (
    auth.uid(), p_institution_id, 'IMPORT_AUTHORIZATION_SET', 'INSTITUTION_MEMBERSHIP', p_membership_id::text,
    jsonb_build_object('can_import', p_can_import, 'can_apply', p_can_apply, 'active', p_active)
  );
end;
$$;

create or replace function public.select_active_institution(p_institution_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1
    from public.institution_membership membership
    join public.app_user app_user on app_user.id = membership.user_id
    where membership.institution_id = p_institution_id
      and membership.user_id = auth.uid()
      and membership.status = 'ACTIVE'
      and app_user.status = 'ACTIVE'
  ) then
    raise exception 'No existe una membresia activa para la institucion indicada.';
  end if;

  insert into public.user_active_institution (user_id, institution_id, selected_at)
  values (auth.uid(), p_institution_id, now())
  on conflict (user_id) do update
    set institution_id = excluded.institution_id,
        selected_at = excluded.selected_at;
end;
$$;

