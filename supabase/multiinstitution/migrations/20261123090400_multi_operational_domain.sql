create or replace function public.assert_identity_scheme_kind()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_kind text;
begin
  select entity_kind into v_kind
  from public.import_identity_scheme
  where id = new.identity_scheme_id
    and institution_id = new.institution_id;

  if v_kind is null then
    raise exception 'El esquema de identidad no pertenece a la institucion indicada.';
  end if;

  if tg_table_name = 'debtor' and v_kind <> 'DEBTOR' then
    raise exception 'El esquema de identidad seleccionado no corresponde a un objeto de deuda.';
  end if;

  if tg_table_name = 'debt' and v_kind <> 'DEBT' then
    raise exception 'El esquema de identidad seleccionado no corresponde a una deuda.';
  end if;

  if tg_table_name = 'person' and v_kind <> 'PERSON' then
    raise exception 'El esquema de identidad seleccionado no corresponde a una persona.';
  end if;

  return new;
end;
$$;

create trigger debtor_identity_scheme_kind_trigger
before insert or update of institution_id, identity_scheme_id on public.debtor
for each row execute function public.assert_identity_scheme_kind();

create trigger person_identity_scheme_kind_trigger
before insert or update of institution_id, identity_scheme_id on public.person
for each row execute function public.assert_identity_scheme_kind();

create trigger debt_identity_scheme_kind_trigger
before insert or update of institution_id, identity_scheme_id on public.debt
for each row execute function public.assert_identity_scheme_kind();

