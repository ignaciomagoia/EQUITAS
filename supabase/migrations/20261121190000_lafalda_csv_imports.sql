create or replace function public.assert_lafalda_import_job(
  p_job_id bigint,
  p_allowed_statuses text[],
  p_require_apply boolean default false
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tenant bigint;
  v_mode text;
  v_status text;
  v_lock_expires_at timestamp with time zone;
begin
  select tenant, mode, status, lock_expires_at
  into v_tenant, v_mode, v_status, v_lock_expires_at
  from public.data_import_job
  where id = p_job_id
  for update;

  if v_tenant is null then
    raise exception 'Importacion inexistente: %', p_job_id;
  end if;

  if v_tenant <> 1 then
    raise exception 'El trabajo % no pertenece al tenant autorizado.', p_job_id;
  end if;

  if not (v_status = any(p_allowed_statuses)) then
    raise exception 'El trabajo % no se encuentra en un estado valido.', p_job_id;
  end if;

  if v_lock_expires_at is null or v_lock_expires_at <= now() then
    raise exception 'El bloqueo del trabajo % vencio.', p_job_id;
  end if;

  if p_require_apply and v_mode <> 'apply' then
    raise exception 'El trabajo % no esta autorizado para aplicar cambios.', p_job_id;
  end if;
end;
$$;

create or replace function public.claim_lafalda_import_job(
  p_worker_id text,
  p_tenant_id bigint
)
returns setof public.data_import_job
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_tenant_id <> 1 then
    raise exception 'Tenant de importacion no autorizado: %', p_tenant_id;
  end if;

  update public.data_import_job job
  set status = case when job.status = 'UPLOADING' then 'CANCELLED' else 'FAILED' end,
      error_message = case
        when job.status = 'UPLOADING' then 'La carga del archivo no finalizo antes de vencer el enlace temporal.'
        else 'El worker dejo de responder y su bloqueo vencio. El trabajo puede reintentarse.'
      end,
      lock_expires_at = null,
      completed_at = now(),
      updated_at = now()
  where job.tenant = p_tenant_id
    and (
      (
        job.status in ('VALIDATING', 'STAGING', 'MERGING', 'RECALCULATING_PROFILES')
        and job.lock_expires_at is not null
        and job.lock_expires_at <= now()
      )
      or (
        job.status = 'UPLOADING'
        and job.created_at <= now() - interval '2 hours'
      )
    );

  return query
  with candidate as (
    select id
    from public.data_import_job
    where status = 'QUEUED'
      and tenant = p_tenant_id
    order by created_at
    for update skip locked
    limit 1
  )
  update public.data_import_job job
  set status = 'VALIDATING',
      worker_id = p_worker_id,
      lock_expires_at = now() + interval '30 minutes',
      attempt_count = job.attempt_count + 1,
      started_at = coalesce(job.started_at, now()),
      updated_at = now(),
      error_message = null
  from candidate
  where job.id = candidate.id
  returning job.*;
end;
$$;

create or replace function public.prepare_lafalda_import_stage(p_job_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tenant bigint;
  v_mode text;
  v_status text;
  v_lock_expires_at timestamp with time zone;
  v_valid_rows integer;
  v_rejected_rows integer;
begin
  select tenant, mode, status, lock_expires_at
  into v_tenant, v_mode, v_status, v_lock_expires_at
  from public.data_import_job
  where id = p_job_id
  for update;

  if v_tenant is null then
    raise exception 'ImportaciÃ³n inexistente: %', p_job_id;
  end if;

  if v_tenant <> 1 then
    raise exception 'El trabajo % no pertenece al tenant autorizado.', p_job_id;
  end if;

  if v_mode not in ('dry_run', 'apply') or v_status <> 'STAGING' then
    raise exception 'El trabajo % no esta listo para preparar staging.', p_job_id;
  end if;

  if v_lock_expires_at is null or v_lock_expires_at <= now() then
    raise exception 'El bloqueo del trabajo % vencio antes de preparar staging.', p_job_id;
  end if;

  insert into public.data_import_row_error (job, source_row, code, message, source_key)
  select
    stage.job,
    stage.source_row,
    'INVALID_CURRENCY',
    'La moneda indicada no existe en el catalogo.',
    jsonb_build_object(
      'bien_tipo_id', stage.debtor_type,
      'cuenta', stage.debtor_external_id,
      'deud_id', stage.debt_external_id
    )
  from public.data_import_debt_stage stage
  where stage.job = p_job_id
    and stage.is_valid
    and stage.currency is not null
    and not exists (select 1 from public.currency where id = stage.currency)
  on conflict (job, source_row, code) do nothing;

  insert into public.data_import_row_error (job, source_row, code, message, source_key)
  select
    stage.job,
    stage.source_row,
    'INVALID_DEBT_STATUS',
    'El estado de deuda indicado no existe en el catalogo.',
    jsonb_build_object(
      'bien_tipo_id', stage.debtor_type,
      'cuenta', stage.debtor_external_id,
      'deud_id', stage.debt_external_id
    )
  from public.data_import_debt_stage stage
  where stage.job = p_job_id
    and stage.is_valid
    and stage.status is not null
    and not exists (select 1 from public.debt_status where id = stage.status)
  on conflict (job, source_row, code) do nothing;

  update public.data_import_debt_stage stage
  set is_valid = false
  where stage.job = p_job_id
    and stage.is_valid
    and (
      (stage.currency is not null and not exists (
        select 1 from public.currency where id = stage.currency
      ))
      or (stage.status is not null and not exists (
        select 1 from public.debt_status where id = stage.status
      ))
    );

  update public.data_import_debt_stage stage
  set debtor_id = debtor.id
  from public.debtor debtor
  where stage.job = p_job_id
    and stage.is_valid
    and debtor.tenant = v_tenant
    and debtor.type = stage.debtor_type
    and debtor.external_id = stage.debtor_external_id;

  insert into public.data_import_row_error (job, source_row, code, message, source_key)
  select
    stage.job,
    stage.source_row,
    'UNKNOWN_DEBTOR',
    'No existe un objeto de deuda para Bien_Tipo_Id + Cuenta dentro del tenant.',
    jsonb_build_object(
      'bien_tipo_id', stage.debtor_type,
      'cuenta', stage.debtor_external_id,
      'deud_id', stage.debt_external_id
    )
  from public.data_import_debt_stage stage
  where stage.job = p_job_id
    and stage.is_valid
    and stage.debtor_id is null
  on conflict (job, source_row, code) do nothing;

  update public.data_import_debt_stage
  set is_valid = false
  where job = p_job_id
    and debtor_id is null;

  insert into public.data_import_row_error (job, source_row, code, message, source_key)
  select
    stage.job,
    stage.source_row,
    'MISSING_REQUIRED_DEBT_DATA',
    'Una deuda nueva requiere importes original y actualizado informados.',
    jsonb_build_object(
      'bien_tipo_id', stage.debtor_type,
      'cuenta', stage.debtor_external_id,
      'deud_id', stage.debt_external_id
    )
  from public.data_import_debt_stage stage
  where stage.job = p_job_id
    and stage.is_valid
    and not exists (
      select 1
      from public.debt debt
      where debt.debtor = stage.debtor_id
        and debt.external_id = stage.debt_external_id
    )
    and (
      stage.original_amount is null
      or stage.current_amount is null
      or not ('original_amount' = any(stage.provided_fields))
      or not ('current_amount' = any(stage.provided_fields))
    )
  on conflict (job, source_row, code) do nothing;

  update public.data_import_debt_stage stage
  set is_valid = false
  where stage.job = p_job_id
    and stage.is_valid
    and not exists (
      select 1
      from public.debt debt
      where debt.debtor = stage.debtor_id
        and debt.external_id = stage.debt_external_id
    )
    and (
      stage.original_amount is null
      or stage.current_amount is null
      or not ('original_amount' = any(stage.provided_fields))
      or not ('current_amount' = any(stage.provided_fields))
    );

  select count(*) into v_valid_rows
  from public.data_import_debt_stage
  where job = p_job_id and is_valid;

  select count(*) into v_rejected_rows
  from public.data_import_row_error
  where job = p_job_id;

  return jsonb_build_object(
    'valid_rows', v_valid_rows,
    'rejected_rows', v_rejected_rows
  );
end;
$$;

create or replace function public.summarize_lafalda_import_stage(p_job_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.assert_lafalda_import_job(
    p_job_id,
    array['STAGING', 'MERGING'],
    false
  );

  return (
    with compared as (
    select
      stage.*,
      debt.id as existing_debt_id,
      case
        when debt.id is null then 'inserted'
        when (
          ('debt_type' = any(stage.provided_fields) and debt.type is distinct from stage.debt_type) or
          ('description' = any(stage.provided_fields) and debt.description is distinct from stage.description) or
          ('original_amount' = any(stage.provided_fields) and debt.original_amount is distinct from stage.original_amount) or
          ('current_amount' = any(stage.provided_fields) and debt.current_amount is distinct from stage.current_amount) or
          ('currency' = any(stage.provided_fields) and debt.currency is distinct from stage.currency) or
          ('issue_date' = any(stage.provided_fields) and debt.issue_date is distinct from stage.issue_date) or
          ('due_date' = any(stage.provided_fields) and debt.due_date is distinct from stage.due_date) or
          ('last_collection_date' = any(stage.provided_fields) and debt.last_collection_date is distinct from stage.last_collection_date) or
          ('period' = any(stage.provided_fields) and debt.period is distinct from stage.period) or
          ('status' = any(stage.provided_fields) and debt.status is distinct from stage.status)
        ) then 'updated'
        else 'unchanged'
      end as comparison
    from public.data_import_debt_stage stage
    left join public.debt debt
      on debt.debtor = stage.debtor_id
      and debt.external_id = stage.debt_external_id
    where stage.job = p_job_id and stage.is_valid
  ), counts as (
    select
      count(*) filter (where comparison = 'inserted') as inserted_rows,
      count(*) filter (where comparison = 'updated') as updated_rows,
      count(*) filter (where comparison = 'unchanged') as unchanged_rows
    from compared
  )
  select jsonb_build_object(
    'inserted_rows', coalesce(inserted_rows, 0),
    'updated_rows', coalesce(updated_rows, 0),
    'unchanged_rows', coalesce(unchanged_rows, 0),
    'rejected_rows', (select count(*) from public.data_import_row_error where job = p_job_id)
  )
    from counts
  );
end;
$$;

create or replace function public.apply_lafalda_import_stage(p_job_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_apply_enabled boolean;
  v_summary jsonb;
  v_updated_rows integer := 0;
  v_inserted_rows integer := 0;
  v_unchanged_rows integer := 0;
  v_rejected_rows integer := 0;
begin
  perform public.assert_lafalda_import_job(
    p_job_id,
    array['MERGING'],
    true
  );

  select apply_enabled
  into v_apply_enabled
  from public.lafalda_import_control
  where tenant = 1
  for share;

  if coalesce(v_apply_enabled, false) is not true then
    raise exception 'La aplicacion de importaciones CSV esta bloqueada a nivel de base de datos.';
  end if;

  v_summary := public.summarize_lafalda_import_stage(p_job_id);

  update public.debt debt
  set type = case when 'debt_type' = any(stage.provided_fields) then stage.debt_type else debt.type end,
      description = case when 'description' = any(stage.provided_fields) then stage.description else debt.description end,
      original_amount = case when 'original_amount' = any(stage.provided_fields) then stage.original_amount else debt.original_amount end,
      current_amount = case when 'current_amount' = any(stage.provided_fields) then stage.current_amount else debt.current_amount end,
      currency = case when 'currency' = any(stage.provided_fields) then stage.currency else debt.currency end,
      issue_date = case when 'issue_date' = any(stage.provided_fields) then stage.issue_date else debt.issue_date end,
      due_date = case when 'due_date' = any(stage.provided_fields) then stage.due_date else debt.due_date end,
      last_collection_date = case when 'last_collection_date' = any(stage.provided_fields) then stage.last_collection_date else debt.last_collection_date end,
      period = case when 'period' = any(stage.provided_fields) then stage.period else debt.period end,
      status = case when 'status' = any(stage.provided_fields) then stage.status else debt.status end
  from public.data_import_debt_stage stage
  where stage.job = p_job_id
    and stage.is_valid
    and debt.debtor = stage.debtor_id
    and debt.external_id = stage.debt_external_id
    and (
      ('debt_type' = any(stage.provided_fields) and debt.type is distinct from stage.debt_type) or
      ('description' = any(stage.provided_fields) and debt.description is distinct from stage.description) or
      ('original_amount' = any(stage.provided_fields) and debt.original_amount is distinct from stage.original_amount) or
      ('current_amount' = any(stage.provided_fields) and debt.current_amount is distinct from stage.current_amount) or
      ('currency' = any(stage.provided_fields) and debt.currency is distinct from stage.currency) or
      ('issue_date' = any(stage.provided_fields) and debt.issue_date is distinct from stage.issue_date) or
      ('due_date' = any(stage.provided_fields) and debt.due_date is distinct from stage.due_date) or
      ('last_collection_date' = any(stage.provided_fields) and debt.last_collection_date is distinct from stage.last_collection_date) or
      ('period' = any(stage.provided_fields) and debt.period is distinct from stage.period) or
      ('status' = any(stage.provided_fields) and debt.status is distinct from stage.status)
    );
  get diagnostics v_updated_rows = row_count;

  insert into public.debt (
    external_id, debtor, type, description, original_amount, current_amount,
    currency, issue_date, due_date, last_collection_date, period, status
  )
  select
    stage.debt_external_id,
    stage.debtor_id,
    stage.debt_type,
    stage.description,
    stage.original_amount,
    stage.current_amount,
    stage.currency,
    stage.issue_date,
    stage.due_date,
    stage.last_collection_date,
    stage.period,
    stage.status
  from public.data_import_debt_stage stage
  left join public.debt existing_debt
    on existing_debt.debtor = stage.debtor_id
    and existing_debt.external_id = stage.debt_external_id
  where stage.job = p_job_id
    and stage.is_valid
    and existing_debt.id is null
    and stage.original_amount is not null
    and stage.current_amount is not null
  on conflict (debtor, external_id) do nothing;
  get diagnostics v_inserted_rows = row_count;

  v_unchanged_rows := greatest(
    coalesce((v_summary ->> 'unchanged_rows')::integer, 0),
    0
  );
  v_rejected_rows := coalesce((v_summary ->> 'rejected_rows')::integer, 0);

  update public.data_import_job
  set inserted_rows = v_inserted_rows,
      updated_rows = v_updated_rows,
      unchanged_rows = v_unchanged_rows,
      rejected_rows = v_rejected_rows,
      updated_at = now()
  where id = p_job_id;

  return jsonb_build_object(
    'inserted_rows', v_inserted_rows,
    'updated_rows', v_updated_rows,
    'unchanged_rows', v_unchanged_rows,
    'rejected_rows', v_rejected_rows
  );
end;
$$;

