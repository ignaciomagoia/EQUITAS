create table if not exists public.telegram_access_link (
  id bigint generated by default as identity primary key,
  tenant bigint not null references public.tenant(id) on delete cascade,
  person bigint not null references public.person(id) on delete cascade,
  token_hash text not null unique,
  telegram_chat_id bigint,
  telegram_username text,
  expires_at timestamp with time zone not null,
  started_at timestamp with time zone,
  active boolean not null default true,
  created_at timestamp with time zone not null default now()
);

create index if not exists telegram_access_link_tenant_person_idx
  on public.telegram_access_link (tenant, person);

create index if not exists telegram_access_link_chat_idx
  on public.telegram_access_link (telegram_chat_id)
  where active and telegram_chat_id is not null;

alter table public.telegram_access_link enable row level security;

revoke all on public.telegram_access_link from anon, authenticated;
grant all on public.telegram_access_link to service_role;
