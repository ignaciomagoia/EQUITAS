do $$
declare
  seed_table_name text;
begin
  foreach seed_table_name in array array['debt', 'debtor_profile', 'debtor_profile_detail']
  loop
    if exists (
      select 1
      from information_schema.columns column_definition
      where column_definition.table_schema = 'public'
        and column_definition.table_name = seed_table_name
        and column_definition.column_name = 'id'
        and column_definition.is_identity = 'NO'
        and column_definition.column_default is null
    ) then
      execute format(
        'alter table public.%I alter column id add generated by default as identity',
        seed_table_name
      );
    end if;
  end loop;
end;
$$;

