-- SOLO PARA EQUITAS-TP-TESTING.
-- Garantiza que las nuevas deudas puedan omitir id, como hace el ETL y la RPC.
-- No modifica IDs ni filas existentes. No ejecutar en Produccion.

do $$
declare
  v_is_identity text;
  v_column_default text;
  v_sequence_name text;
  v_max_id bigint;
begin
  select is_identity, column_default
  into v_is_identity, v_column_default
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'debt'
    and column_name = 'id';

  if not found then
    raise exception 'No existe la columna public.debt.id.';
  end if;

  if v_is_identity = 'NO' and v_column_default is null then
    if exists (
      select 1
      from pg_trigger trigger
      join pg_class relation on relation.oid = trigger.tgrelid
      join pg_namespace namespace on namespace.oid = relation.relnamespace
      where namespace.nspname = 'public'
        and relation.relname = 'debt'
        and not trigger.tgisinternal
    ) then
      raise exception
        'public.debt tiene triggers personalizados. Revise diagnostico_debt_id_generation.sql antes de agregar identidad.';
    end if;

    alter table public.debt
      alter column id add generated by default as identity;
  elsif v_is_identity = 'NO' and v_column_default not like 'nextval(%' then
    raise exception
      'public.debt.id tiene un default no secuencial. Revise diagnostico_debt_id_generation.sql antes de continuar.';
  end if;

  select pg_get_serial_sequence('public.debt', 'id')
  into v_sequence_name;

  if v_sequence_name is null then
    raise exception 'No se pudo determinar la secuencia de public.debt.id.';
  end if;

  select max(id) into v_max_id from public.debt;

  if v_max_id is null then
    perform setval(v_sequence_name::regclass, 1, false);
  else
    perform setval(v_sequence_name::regclass, v_max_id, true);
  end if;
end;
$$;
